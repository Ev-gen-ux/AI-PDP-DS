import StyleDictionary from 'style-dictionary';
import { register } from '@tokens-studio/sd-transforms';

/**
 * Style Dictionary 5.x config (ESM).
 *
 * Источник: /tokens (W3C DTCG JSON, синхронизирован с Figma).
 * Целевые форматы:
 *   1) src/theme/variables.css — CSS Custom Properties для всех тем и брейкпоинтов
 *   2) src/theme/tokens.ts     — TypeScript-объект для <ThemeProvider>
 *   3) dist/figma.tokens.json  — формат для пуша в Figma Variables REST API
 */

const cssNameTransform = (token) => token.path.join('-');

StyleDictionary.registerTransform({
  name: 'name/css/kebab',
  type: 'name',
  transform: (token) => cssNameTransform(token),
});

StyleDictionary.registerFormat({
  name: 'css/themed-variables',
  format: ({ dictionary, options }) => {
    const { themeName, selector } = options;
    const lines = dictionary.allTokens.map(
      (t) => `  --${cssNameTransform(t)}: ${t.$value ?? t.value};`,
    );
    return `/* Theme: ${themeName} */\n${selector} {\n${lines.join('\n')}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'typescript/theme-object',
  format: ({ dictionary }) => {
    const tree = {};
    for (const token of dictionary.allTokens) {
      let cursor = tree;
      const path = token.path;
      for (let i = 0; i < path.length - 1; i++) {
        cursor[path[i]] = cursor[path[i]] || {};
        cursor = cursor[path[i]];
      }
      cursor[path[path.length - 1]] = `var(--${cssNameTransform(token)})`;
    }
    return [
      '// AUTOGENERATED by Style Dictionary. Do not edit by hand.',
      '// Source: /tokens',
      '',
      `export const theme = ${JSON.stringify(tree, null, 2)} as const;`,
      '',
      'export type Theme = typeof theme;',
      '',
    ].join('\n');
  },
});

export default {
  source: ['tokens/**/*.json'],
  platforms: {
    'css-light': {
      transformGroup: 'css',
      buildPath: 'src/theme/',
      files: [
        {
          destination: 'variables.light.css',
          format: 'css/themed-variables',
          filter: (token) => token.filePath.includes('semantic') === false || token.filePath.includes('light'),
          options: { themeName: 'light', selector: ':root, [data-theme="light"]' },
        },
      ],
    },
    'css-dark': {
      transformGroup: 'css',
      buildPath: 'src/theme/',
      files: [
        {
          destination: 'variables.dark.css',
          format: 'css/themed-variables',
          filter: (token) => token.filePath.includes('dark'),
          options: { themeName: 'dark', selector: '[data-theme="dark"]' },
        },
      ],
    },
    typescript: {
      transformGroup: 'js',
      buildPath: 'src/theme/',
      files: [
        {
          destination: 'tokens.ts',
          format: 'typescript/theme-object',
        },
      ],
    },
    figma: {
      transformGroup: 'js',
      buildPath: 'dist/',
      files: [
        {
          destination: 'figma.tokens.json',
          format: 'json/nested',
        },
      ],
    },
  },
};
