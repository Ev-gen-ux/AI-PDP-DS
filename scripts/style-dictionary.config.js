import StyleDictionary from 'style-dictionary';

const toCssVarName = (path) => path.join('-');
const getNormalizedPath = (token) => {
  const fileName = token.filePath.split('/').pop() || '';
  if (fileName.startsWith('typography.')) {
    return token.path.slice(1);
  }
  return token.path;
};
const appendToken = (tree, path, value) => {
  let cursor = tree;
  for (let index = 0; index < path.length - 1; index += 1) {
    const segment = path[index];
    cursor[segment] = cursor[segment] || {};
    cursor = cursor[segment];
  }
  cursor[path[path.length - 1]] = value;
};

const serializeObject = (object, indent = 0) => {
  const spacing = '  '.repeat(indent);
  const entries = Object.entries(object);
  if (entries.length === 0) {
    return '{}';
  }
  const lines = entries.map(([key, value]) => {
    const serializedValue =
      value && typeof value === 'object'
        ? serializeObject(value, indent + 1)
        : `"${String(value)}"`;
    return `${'  '.repeat(indent + 1)}${key}: ${serializedValue}`;
  });
  return `{\n${lines.join(',\n')}\n${spacing}}`;
};

StyleDictionary.registerTransform({
  name: 'name/css/kebab',
  type: 'name',
  transform: (token) => toCssVarName(token.path),
});

StyleDictionary.registerFormat({
  name: 'css/theme-light',
  format: ({ dictionary }) => {
    const baseTokens = dictionary.allTokens.filter(
      (token) =>
        token.filePath.includes('/primitives/') ||
        token.filePath.endsWith('spacing.json') ||
        token.filePath.endsWith('borderRadius.json') ||
        token.filePath.endsWith('colors.light-theme.json'),
    );
    const typographyXl = dictionary.allTokens.filter((token) =>
      token.filePath.endsWith('typography.xl.json'),
    );
    const typographyMd = dictionary.allTokens.filter((token) =>
      token.filePath.endsWith('typography.md.json'),
    );
    const typographyXs = dictionary.allTokens.filter((token) =>
      token.filePath.endsWith('typography.xs.json'),
    );

    const toLine = (token) => `  --${toCssVarName(getNormalizedPath(token))}: ${token.value};`;
    return [
      '/* AUTOGENERATED by Style Dictionary. Do not edit by hand. */',
      ':root, [data-theme="light"] {',
      ...baseTokens.map(toLine),
      ...typographyXl.map(toLine),
      '}',
      '',
      '@media (max-width: 1279px) {',
      '  :root, [data-theme="light"] {',
      ...typographyMd.map(
        (token) => `    --${toCssVarName(getNormalizedPath(token))}: ${token.value};`,
      ),
      '  }',
      '}',
      '',
      '@media (max-width: 767px) {',
      '  :root, [data-theme="light"] {',
      ...typographyXs.map(
        (token) => `    --${toCssVarName(getNormalizedPath(token))}: ${token.value};`,
      ),
      '  }',
      '}',
      '',
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'css/theme-dark',
  format: ({ dictionary }) => {
    const tokens = dictionary.allTokens.filter((token) =>
      token.filePath.endsWith('colors.dark-theme.json'),
    );
    return [
      '/* AUTOGENERATED by Style Dictionary. Do not edit by hand. */',
      '[data-theme="dark"] {',
      ...tokens.map((token) => `  --${toCssVarName(getNormalizedPath(token))}: ${token.value};`),
      '}',
      '',
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'typescript/theme-object',
  format: ({ dictionary }) => {
    const root = {};
    const semanticTokens = dictionary.allTokens.filter(
      (token) =>
        token.filePath.endsWith('spacing.json') ||
        token.filePath.endsWith('borderRadius.json') ||
        token.filePath.endsWith('typography.xl.json') ||
        token.filePath.endsWith('colors.light-theme.json'),
    );

    for (const token of semanticTokens) {
      const fileName = token.filePath.split('/').pop() || '';
      let path = getNormalizedPath(token);
      if (fileName.startsWith('colors.')) {
        path = ['colors', ...token.path];
      } else if (fileName === 'spacing.json') {
        path = ['spacing', ...token.path];
      } else if (fileName === 'borderRadius.json') {
        path = ['borderRadius', ...token.path];
      } else if (fileName.startsWith('typography.')) {
        path = ['typography', ...getNormalizedPath(token)];
      }
      appendToken(root, path, `var(--${toCssVarName(path)})`);
    }

    return [
      '// AUTOGENERATED by Style Dictionary. Do not edit by hand.',
      '',
      `export const theme = ${serializeObject(root)} as const;`,
      '',
      'export type Theme = typeof theme;',
      '',
    ].join('\n');
  },
});

